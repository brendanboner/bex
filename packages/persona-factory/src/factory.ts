import { generateObject } from 'ai';
import { z } from 'zod';
import type { PrismaClient, Persona } from '@prisma/client';
import { buildModel } from '@bex/skill-engine';
import { KnowledgeStore } from '@bex/knowledge-store';
import type { LlmProvider } from '@bex/shared';

export interface GeneratePersonaOptions {
  goal: string;
  domain?: string;
  existingSkills?: string[];
  schedule?: string; // explicit cron override — skips LLM inference
}

export interface GeneratedPersona {
  id: string;
  name: string;
  goal: string;
  domain?: string;
  systemPrompt: string;
  requiredSkills: string[];
  suggestedPermissions: string[];
  schedule?: string;
  tags: string[];
  /** Workspace docs generated by LLM, stored in KnowledgeStore under agent/{personaId} */
  workspaceDocs?: {
    instructions: string;
    context: string;
    memory: string;
  };
}

const PersonaSchema = z.object({
  name: z.string().describe('Short descriptive agent name'),
  systemPrompt: z.string().describe('Full system prompt for the agent'),
  requiredSkills: z.array(z.string()).describe('Skill domain identifiers needed'),
  suggestedPermissions: z
    .array(z.string())
    .describe('Permission strings needed (e.g. read:network, ssh:exec)'),
  schedule: z
    .string()
    .optional()
    .describe('Cron expression if this agent should run on a schedule'),
  tags: z.array(z.string()).describe('Discovery tags'),
  rationale: z.string().describe('Brief explanation of design choices'),
  instructions: z
    .string()
    .describe(
      'Detailed operational instructions document (markdown). ' +
      'Covers: how to behave, what to check, response format, escalation rules, limits.',
    ),
  context: z
    .string()
    .describe(
      'Environment context document (markdown). ' +
      'Covers: relevant systems, topology, key facts the agent should always know.',
    ),
  memory: z
    .string()
    .describe(
      'Memory template document (markdown). ' +
      'A template of what the agent should record after each run: observations, changes, open items.',
    ),
});

export class PersonaFactory {
  private knowledgeStore: KnowledgeStore;

  constructor(
    private prisma: PrismaClient,
    private llmProvider: string = 'openai',
    private llmModel: string = 'gpt-4o',
  ) {
    this.knowledgeStore = new KnowledgeStore(process.env['KNOWLEDGE_BASE_DIR'] ?? './knowledge');
  }

  async generate(options: GeneratePersonaOptions): Promise<GeneratedPersona> {
    const model = buildModel(this.llmProvider as LlmProvider);

    const domainHint = options.domain ? `\nDomain hint: ${options.domain}` : '';
    const skillsHint =
      options.existingSkills && options.existingSkills.length > 0
        ? `\nAvailable skill domains: ${options.existingSkills.join(', ')}`
        : '';

    const { object } = await generateObject({
      model,
      schema: PersonaSchema,
      system:
        'You are an expert agentic system designer. Given a natural-language goal, ' +
        'design a complete agent persona with a detailed "soul". ' +
        'Be specific about required skills (use dot-separated domain identifiers like "networking.extreme-xco"), ' +
        'permissions, and system prompts. ' +
        'For the instructions doc, write detailed operational rules the agent will follow on every run. ' +
        'For the context doc, describe the environment and system facts. ' +
        'For the memory doc, write a template the agent fills in after each run. ' +
        'Only set a cron schedule if the goal implies periodic/automated execution.',
      prompt: `Goal: ${options.goal}${domainHint}${skillsHint}`,
    });

    const created = await this.prisma.persona.create({
      data: {
        name: object.name,
        goal: options.goal,
        ...(options.domain !== undefined ? { domain: options.domain } : {}),
        systemPrompt: object.systemPrompt,
        requiredSkills: object.requiredSkills,
        suggestedPermissions: object.suggestedPermissions,
        schedule: options.schedule ?? object.schedule ?? null,
        tags: object.tags,
      },
    });

    // Store workspace docs in KnowledgeStore keyed by persona ID
    const personaDomain = `agent/${created.id}`;
    await Promise.all([
      this.knowledgeStore.write(personaDomain, 'instructions', object.instructions),
      this.knowledgeStore.write(personaDomain, 'context', object.context),
      this.knowledgeStore.write(personaDomain, 'memory', object.memory),
    ]);

    return {
      id: created.id,
      name: created.name,
      goal: created.goal,
      ...(created.domain != null ? { domain: created.domain } : {}),
      systemPrompt: created.systemPrompt,
      requiredSkills: created.requiredSkills,
      suggestedPermissions: created.suggestedPermissions,
      ...(created.schedule != null ? { schedule: created.schedule } : {}),
      tags: created.tags,
      workspaceDocs: {
        instructions: object.instructions,
        context: object.context,
        memory: object.memory,
      },
    };
  }

  async list(domain?: string): Promise<Persona[]> {
    return this.prisma.persona.findMany({
      ...(domain !== undefined ? { where: { domain } } : {}),
      orderBy: { createdAt: 'desc' },
    });
  }

  async get(id: string): Promise<Persona | null> {
    return this.prisma.persona.findUnique({ where: { id } });
  }
}
